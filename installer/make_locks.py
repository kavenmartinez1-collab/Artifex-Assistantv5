"""Developer tool: turn exact package pins into hash-locked requirement files.

    python -m installer.make_locks core installer/pins-core.txt
    python -m installer.make_locks gui  installer/pins-gui.txt

Reads name==version lines, asks PyPI's JSON API for the SHA-256 of every
WHEEL of that exact version, and writes installer/requirements-<name>.txt
with a --hash line per wheel. Source distributions are left out on purpose:
the installer runs pip with --only-binary=:all:, because building an sdist
executes its setup code.

This runs on a developer's machine when pins change, never during an
install. The installer only reads the committed lock files, and pip
(--require-hashes) refuses any file whose hash isn't in them.
"""

import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
_PIN = re.compile(r"^\s*([A-Za-z0-9_.\-]+)==([A-Za-z0-9_.+\-]+)\s*(?:#.*)?$")


def wheel_hashes(name: str, version: str) -> list:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    hashes = sorted({f["digests"]["sha256"] for f in data.get("urls", [])
                     if f.get("packagetype") == "bdist_wheel" and not f.get("yanked")})
    if not hashes:
        raise SystemExit(f"{name}=={version} has no wheels on PyPI; it can't be "
                         "installed with --only-binary, pick another version")
    return hashes


def make(lock_name: str, pins_path: str) -> str:
    pins = []
    for line in open(pins_path, encoding="utf-8"):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = _PIN.match(line)
        if not m:
            raise SystemExit(f"not an exact pin: {line.strip()!r}")
        pins.append((m.group(1), m.group(2)))
    out = os.path.join(HERE, f"requirements-{lock_name}.txt")
    lines = [f"# GENERATED by python -m installer.make_locks {lock_name} {os.path.relpath(pins_path)}",
             "# Do not edit by hand: change the pins file and regenerate.",
             "# Install with: pip install --require-hashes --only-binary=:all: -r <this file>",
             ""]
    for name, version in sorted(pins, key=lambda p: p[0].lower()):
        hs = wheel_hashes(name, version)
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "")
                  for i, h in enumerate(hs)]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    print("wrote", make(sys.argv[1], sys.argv[2]))
